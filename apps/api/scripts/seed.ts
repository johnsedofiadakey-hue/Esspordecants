// Seeds the Firebase emulators with an owner account and clearly synthetic sample
// records. Sample products are flagged isSample and can never be published.
// Refuses to run against a live project.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadConfig } from "../src/config.ts";
import { COLLECTIONS, openStore } from "../src/firebase.ts";
import { newId, now, randomToken } from "../src/lib/util.ts";
import { makeEvent, type OrderDoc } from "../src/services/orders.ts";
import { emptyProduct, finalize, type VariantRec } from "../src/services/products.ts";
import { createAdmin } from "../src/routes/admin/users.ts";

if (!process.env.FIRESTORE_EMULATOR_HOST || !process.env.FIREBASE_AUTH_EMULATOR_HOST) {
  console.error("Refusing to seed: run this against the emulators (npm run seed uses .env.emulators).");
  process.exit(1);
}

const config = loadConfig();
const store = openStore(config);
const dataDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../data");

async function seedAdmin() {
  const email = (process.env.SEED_ADMIN_EMAIL || "admin@esspor.local").toLowerCase();
  try {
    await store.auth.getUserByEmail(email);
    console.log(`Admin ${email} already exists; leaving its password unchanged.`);
    return;
  } catch {
    // not found: create below
  }
  const password = process.env.SEED_ADMIN_PASSWORD || randomToken(18);
  await createAdmin(store, { email, name: "Local Owner", role: "owner", password });
  if (process.env.SEED_ADMIN_PASSWORD) {
    console.log(`Created owner ${email} with the password from SEED_ADMIN_PASSWORD.`);
    return;
  }
  fs.mkdirSync(dataDir, { recursive: true });
  const file = path.join(dataDir, "dev-admin-credentials.txt");
  fs.writeFileSync(file, `Local emulator admin (generated by npm run seed)\nemail: ${email}\npassword: ${password}\n`, { mode: 0o600 });
  console.log(`Created owner ${email}. Generated password written to ${path.relative(process.cwd(), file)} (not printed).`);
}

const samples = [
  { slug: "sample-amber-study", house: "Sample House", name: "Synthetic Amber Study", concentration: "Eau de Parfum", family: "Amber", sizes: [[2, 4500, 12], [5, 9500, 6], [10, 17500, 2]] },
  { slug: "sample-citrus-study", house: "Sample House", name: "Synthetic Citrus Study", concentration: "Eau de Toilette", family: "Citrus", sizes: [[2, 3500, 0], [5, 7500, 9], [10, 13500, 4]] },
  { slug: "sample-woody-study", house: "Example Atelier", name: "Synthetic Woody Study", concentration: "Extrait de Parfum", family: "Woody", sizes: [[2, 6000, 20], [5, 13000, 10], [10, 24000, 5]] },
] as const;

type SeededVariant = { productId: string; house: string; name: string; variant: VariantRec };

async function seedSamples(): Promise<SeededVariant[]> {
  const seeded: SeededVariant[] = [];
  const batch = store.db.batch();
  for (const sample of samples) {
    const id = newId();
    const product = emptyProduct(sample.house, sample.name, sample.slug);
    Object.assign(product, {
      concentration: sample.concentration,
      family: sample.family,
      shortDescription: "SYNTHETIC SAMPLE — not a real product. For local admin testing only.",
      description: "This record exists to exercise the admin portal. It is flagged as sample data and cannot be published.",
      notes: { top: ["Bergamot"], heart: ["Iris"], base: ["Cedar"] },
      sourceBrand: "Sample source brand",
      authenticityCopy: "Sample authenticity copy. Replace with approved wording.",
      whatArrives: "Sample: one glass decant with atomiser.",
      physical: { bottleMaterial: "Glass (pending merchant confirmation)", capType: "Spray atomiser (pending confirmation)", labelVersion: "Draft label v0", packagingNotes: "" },
      isSample: true,
    });
    product.variants = sample.sizes.map(([size, price, stock], index) => ({
      id: newId(),
      sku: `SMP-${sample.slug.split("-")[1]!.toUpperCase()}-${size}`,
      sizeMl: size,
      priceMinor: price,
      stockQuantity: stock,
      lowStockThreshold: 3,
      active: true,
      bottleDiffers: false,
      imageId: null,
      packagingNotes: "",
      sortOrder: index,
    }));
    batch.set(store.db.collection(COLLECTIONS.products).doc(id), finalize(product));
    for (const variant of product.variants) seeded.push({ productId: id, house: sample.house, name: sample.name, variant });
  }
  await batch.commit();
  return seeded;
}

async function seedOrders(variants: SeededVariant[]) {
  const plans = [
    { status: "pending_payment", payment: "not_configured", lines: [[1, 1], [4, 2]], daysAgo: 0 },
    { status: "paid", payment: "paid", lines: [[7, 1]], daysAgo: 2 },
    { status: "shipped", payment: "paid", lines: [[2, 1], [5, 1]], daysAgo: 6 },
  ] as const;
  let number = 1000;
  const batch = store.db.batch();
  plans.forEach((plan, index) => {
    const created = new Date(Date.now() - plan.daysAgo * 86_400_000).toISOString();
    const items = plan.lines.map(([variantIndex, quantity]) => {
      const { productId, house, name, variant } = variants[variantIndex]!;
      return { id: newId(), variantId: variant.id, productId, sku: variant.sku, house, name, sizeMl: variant.sizeMl, unitPriceMinor: variant.priceMinor, quantity, lineTotalMinor: variant.priceMinor * quantity };
    });
    const subtotal = items.reduce((sum, item) => sum + item.lineTotalMinor, 0);
    const events = [makeEvent("created", { to: "pending_payment", note: "Synthetic sample order.", at: created })];
    if (plan.status !== "pending_payment") events.push(makeEvent("status", { from: "pending_payment", to: plan.status, note: "Synthetic history.", at: created }));
    const order: OrderDoc = {
      number: `ESS-${number++}`,
      status: plan.status,
      paymentStatus: plan.payment,
      paymentProvider: "none",
      paymentReference: null,
      customerName: `Synthetic Customer ${index + 1}`,
      customerEmail: `customer${index + 1}@example.invalid`,
      customerPhone: "+233 00 000 0000",
      deliveryAddress: { line1: "1 Example Street", city: "Accra", region: "Greater Accra" },
      deliveryOptionCode: null,
      deliveryLabel: "Sample delivery (unconfirmed)",
      subtotalMinor: subtotal,
      deliveryMinor: 0,
      totalMinor: subtotal,
      currency: "GHS",
      internalNotes: "Synthetic order for admin testing.",
      isSample: true,
      items,
      productIds: [...new Set(items.map((item) => item.productId))],
      variantIds: items.map((item) => item.variantId),
      events,
      createdAt: created,
      updatedAt: created,
    };
    batch.set(store.db.collection(COLLECTIONS.orders).doc(newId()), order);
  });
  batch.set(store.db.collection(COLLECTIONS.counters).doc("orders"), { value: number - 1 });
  await batch.commit();
}

async function seedContentAndDelivery() {
  const timestamp = now();
  const base = { status: "draft", image: null, imageId: null, publicFiles: [], sortOrder: 0, publishedAt: null, createdAt: timestamp, updatedAt: timestamp };
  const batch = store.db.batch();
  batch.set(store.db.collection(COLLECTIONS.content).doc(newId()), {
    ...base, slug: "home-hero", placement: "home-hero", eyebrow: "Authentic decants", title: "Discover more. Commit to less.", body: "", ctaLabel: "Shop decants", ctaHref: "/shop",
  });
  batch.set(store.db.collection(COLLECTIONS.content).doc(newId()), {
    ...base, slug: "about-esspor", placement: "home-story", eyebrow: "Our promise", title: "Sample story copy", body: "SYNTHETIC SAMPLE — replace with approved Esspor copy before publishing.", ctaLabel: "", ctaHref: "",
  });
  // Inactive until the delivery policy is confirmed.
  batch.set(store.db.collection(COLLECTIONS.delivery).doc("example-courier"), {
    code: "example-courier", label: "Example courier (unconfirmed)", description: "Placeholder until delivery rules are agreed.", priceMinor: 2500, active: false, sortOrder: 0, createdAt: timestamp, updatedAt: timestamp,
  });
  await batch.commit();
}

await seedAdmin();
const marker = store.db.collection(COLLECTIONS.counters).doc("sampleSeeded");
if ((await marker.get()).exists) {
  console.log("Sample data already present; skipped.");
} else {
  await seedOrders(await seedSamples());
  await seedContentAndDelivery();
  await marker.set({ at: now() });
  console.log("Seeded 3 synthetic draft products, 3 synthetic orders, 2 draft content entries, 1 inactive delivery option.");
}
process.exit(0);
